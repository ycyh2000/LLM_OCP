class AdamW_galore(Optimizer):
    """
    Implements AdamW with optional GaLore gradient projection.
    """

    def __init__(
        self,
        params,
        lr=1e-3,
        betas=(0.9, 0.98),
        eps=1e-6,
        weight_decay=0.0,
        correct_bias=True,
        galore_rank=4,
        update_proj_gap=200,
        scale=1.0,
        proj_type='std'
    ):
        if lr < 0.0:
            raise ValueError(f"Invalid learning rate: {lr} - should be >= 0.0")
        if not 0.0 <= betas[0] < 1.0:
            raise ValueError(f"Invalid beta parameter: {betas[0]} - should be in [0.0, 1.0)")
        if not 0.0 <= betas[1] < 1.0:
            raise ValueError(f"Invalid beta parameter: {betas[1]} - should be in [0.0, 1.0)")
        if not 0.0 <= eps:
            raise ValueError(f"Invalid epsilon value: {eps} - should be >= 0.0")

        defaults = dict(
            lr=lr,
            betas=betas,
            eps=eps,
            weight_decay=weight_decay,
            correct_bias=correct_bias,
            galore_rank=galore_rank,
            update_proj_gap=update_proj_gap,
            scale=scale,
            proj_type=proj_type
        )
        super().__init__(params, defaults)

    def reset_state(self):
        for group in self.param_groups:
            for p in group['params']:
                state = self.state[p]
                state['step'] = 0
                state["exp_avg"] = torch.zeros_like(p.data)
                state["exp_avg_sq"] = torch.zeros_like(p.data)

    @torch.no_grad()
    def step(self, closure=None):
        """
        Performs a single optimization step.
        """
        loss = None
        if closure is not None:
            loss = closure()

        for group in self.param_groups:
            for p in group["params"]:
                if p.grad is None:
                    continue

                grad = p.grad

                if grad.is_sparse:
                    raise RuntimeError("Adam does not support sparse gradients, please consider SparseAdam instead")

                state = self.state[p]

                if "step" not in state:
                    state["step"] = 0

                if "dim" not in group:
                    group["dim"] = 2


                # GaLore projection
                if "galore_rank" in group:
                    if "projector" not in state:
                        if group["dim"] <= 2:
                            state["projector"] = GaLoreProjector(
                                group["galore_rank"],
                                update_proj_gap=group["update_proj_gap"],
                                scale=group["scale"],
                                proj_type=group["proj_type"]
                            )
                        else:
                            state["projector"] = GaLoreProjectorTensor(
                                group["galore_rank"],
                                update_proj_gap=group["update_proj_gap"],
                                scale=group["scale"],
                                proj_type=group["proj_type"]
                            )

                    if grad.dim() >= 2:
                        start = time.perf_counter()

                        grad = state["projector"].project(grad, state["step"])


                        # param_name = getattr(self, "param_name_map", {}).get(id(p), "unknown")
                        #
                        # print(
                        #     f"[DEBUG] call save func: param={param_name}, step={state['step']}, grad_shape={tuple(grad.shape)}")
                        #
                        # save_galore_subspace_if_needed(
                        #     param_name=param_name,
                        #     p=p,
                        #     state=state,
                        #     group=group
                        # )
                        #
                        # end = time.perf_counter()
                        #
                        # if param_name != "unknown" and any(
                        #     key in param_name for key in [
                        #         "h.2.attn.c_attn.weight",
                        #         "h.2.mlp.c_fc.weight",
                        #         "h.12.attn.c_attn.weight",
                        #         "h.12.mlp.c_fc.weight",
                        #         "h.22.attn.c_attn.weight",
                        #         "h.22.mlp.c_fc.weight",
                        #     ]
                        # ):
                        #     print(
                        #         f"[GaLore projector] param={param_name}, "
                        #         f"step={state['step']}, "
                        #         f"time={(end - start) * 1000:.2f} ms"
                        #     )

                # State initialization
                if "exp_avg" not in state:
                    state["exp_avg"] = torch.zeros_like(grad)
                    state["exp_avg_sq"] = torch.zeros_like(grad)

                exp_avg, exp_avg_sq = state["exp_avg"], state["exp_avg_sq"]
                beta1, beta2 = group["betas"]

                state["step"] += 1

                exp_avg.mul_(beta1).add_(grad, alpha=(1.0 - beta1))
                exp_avg_sq.mul_(beta2).addcmul_(grad, grad, value=1.0 - beta2)

                denom = exp_avg_sq.sqrt().add_(group["eps"])

                step_size = group["lr"]
                if group["correct_bias"]:
                    bias_correction1 = 1.0 - beta1 ** state["step"]
                    bias_correction2 = 1.0 - beta2 ** state["step"]
                    step_size = step_size * math.sqrt(bias_correction2) / bias_correction1

                norm_grad = exp_avg / denom

                # GaLore projection back
                if "galore_rank" in group:
                    if grad.dim() >= 2:
                        norm_grad = state["projector"].project_back(norm_grad)

                p.add_(norm_grad, alpha=-step_size)

                if group["weight_decay"] > 0.0:
                    p.add_(p, alpha=(-group["lr"] * group["weight_decay"]))

        return loss
