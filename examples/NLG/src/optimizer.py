def save_galore_subspace_if_needed(param_name, p, state, group):
    """
    Save the GaLore projection matrix for selected layers.

    This function saves only the projection matrix generated by GaLore,
    not the full gradient tensor.
    """
    rank_id = int(os.environ.get("RANK", "0"))
    if rank_id != 0:
        return

    target_keywords = [
        "h.2.attn.c_attn.weight",
        "h.2.mlp.c_fc.weight",
        "h.12.attn.c_attn.weight",
        "h.12.mlp.c_fc.weight",
        "h.22.attn.c_attn.weight",
        "h.22.mlp.c_fc.weight",
    ]

    if not any(key in param_name for key in target_keywords):
        return

    if state["step"] % group["update_proj_gap"] != 0:
        return

    if "projector" not in state:
        return

    projector = state["projector"]

    if not hasattr(projector, "ortho_matrix"):
        return

    if projector.ortho_matrix is None:
        return

    save_dir = os.path.abspath(
        os.path.join(
            "./subspace",
            f"rank_{group['galore_rank']}_gap_{group['update_proj_gap']}"
        )
    )
    os.makedirs(save_dir, exist_ok=True)

    safe_name = param_name.replace(".", "_")
    save_path = os.path.join(save_dir, f"{safe_name}_step_{state['step']}.pt")

    torch.save(
        {
            "step": state["step"],
            "param_name": param_name,
            "grad_shape": tuple(p.grad.shape),
            "ortho_matrix": projector.ortho_matrix.detach().cpu(),
        },
        save_path
    )

    print(f"[Saved GaLore subspace] {save_path}")


